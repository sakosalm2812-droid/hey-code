export function getHeyV1AgentBySpecId(specId) {
  return heyV1AgentCatalog.find((agent) => agent.specId === Number(specId)) || null;
}

export function searchHeyV1Agents(query = "") {
  const q = String(query).trim().toLowerCase();
  if (!q) return [...heyV1AgentCatalog];
  return heyV1AgentCatalog.filter((agent) =>
    [agent.name, agent.role, agent.category, agent.description, ...(agent.capabilities || [])]
      .join(" ")
      .toLowerCase()
      .includes(q)
  );
}

